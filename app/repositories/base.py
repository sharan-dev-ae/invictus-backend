from typing import Protocol
from app.schemas import PlanIn, BucketIn

class Repository(Protocol):
    def list_plans(self,owner_id:str|None=None)->list[dict]: ...
    def create_plan(self,body:PlanIn,owner_id:str|None=None)->dict: ...
    def update_plan(self,pid:str,changes:dict,owner_id:str|None=None)->dict|None: ...
    def delete_plan(self,pid:str,owner_id:str|None=None)->bool: ...
    def list_bucket_items(self,owner_id:str|None=None)->list[dict]: ...
    def create_bucket_item(self,body:BucketIn,owner_id:str|None=None)->dict: ...
    def health(self)->bool: ...
    def workspace(self,owner_id:str)->dict: ...
    def create_project(self,body,owner_id:str)->dict: ...
    def create_milestone(self,body,owner_id:str)->dict: ...
    def create_task(self,body,owner_id:str)->dict: ...
    def update_task(self,task_id:str,changes:dict,owner_id:str)->dict|None: ...
    def delete_task(self,task_id:str,owner_id:str)->bool: ...
